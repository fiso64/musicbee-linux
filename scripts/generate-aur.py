#!/usr/bin/env python3
"""Generate standalone AUR files from the shared nFPM configuration."""
import argparse
from pathlib import Path, PurePosixPath
import re
import runpy
import shlex

import yaml


ROOT = Path(__file__).resolve().parents[1]


def generate(config: dict, version: str, commit: str) -> tuple[str, str]:
    if not re.fullmatch(r'[0-9]+\.[0-9]+\.[0-9]+', version):
        raise ValueError('Expected a release version like 1.2.3')
    if not re.fullmatch(r'[0-9a-f]{40}', commit):
        raise ValueError('Expected a full lowercase Git commit ID')
    name = config['name'] + '-linux'
    arch = config['overrides']['archlinux']
    source = f"{name}::git+{config['homepage']}.git#commit={commit}"
    values = {
        'pkgname': name,
        'pkgver': version,
        'pkgrel': str(config['release']),
        'pkgdesc': config['description'].splitlines()[0],
        'url': config['homepage'],
    }
    arrays = {
        'arch': ['any' if config['arch'] == 'all' else config['arch']],
        'license': [config['license']],
        'makedepends': ['git'],
        'depends': arch['depends'],
        'optdepends': arch.get('suggests', []),
        'provides': [config['name']],
        'conflicts': [config['name']],
        'source': [source],
        'sha256sums': ['SKIP'],  # Git verifies the pinned object ID.
    }
    q = shlex.quote
    lines = [f"# Maintainer: {config['maintainer']}",
             '# Generated by scripts/generate-aur.py; edit packaging/nfpm/nfpm.yaml instead.']
    for key, value in values.items():
        lines.append(f'{key}={q(value)}')
    for key, items in arrays.items():
        if items:
            lines.append(f"{key}=({' '.join(q(str(item)) for item in items)})")
    lines += ['', 'package() {', f'  cd "$srcdir"/{q(name)}']
    for item in config['contents']:
        src, dst = PurePosixPath(item['src']), PurePosixPath(item['dst'])
        if src.is_absolute() or '..' in src.parts or not dst.is_absolute() or '..' in dst.parts:
            raise ValueError(f'Unsupported package path: {src} -> {dst}')
        if item.get('type') or set(item) - {'src', 'dst', 'file_info'}:
            raise ValueError(f'Unsupported nFPM content entry: {item}')
        mode = item.get('file_info', {}).get('mode', 0o644)
        if isinstance(mode, str):
            mode = int(mode, 8)
        if '*' in src.name:
            if src.name != '*.py' or src.parent != PurePosixPath('src/musicbee_linux'):
                raise ValueError(f'Unsupported package glob: {src}')
            lines.append(f'  for file in {src.parent}/*.py; do install -Dm{mode:03o} "$file" "$pkgdir"{q(str(dst))}/"${{file##*/}}"; done')
        else:
            lines.append(f'  install -Dm{mode:03o} {q(str(src))} "$pkgdir"{q(str(dst))}')
    lines += ['}', '']
    srcinfo = [f'pkgbase = {name}']
    for key in ('pkgdesc', 'pkgver', 'pkgrel', 'url'):
        srcinfo.append(f'\t{key} = {values[key]}')
    for key, items in arrays.items():
        for item in items:
            srcinfo.append(f'\t{key} = {item}')
    srcinfo += ['', f'pkgname = {name}', '']
    return '\n'.join(lines), '\n'.join(srcinfo)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--commit', required=True, help='Full commit ID to package')
    parser.add_argument('--output', required=True, type=Path, help='Output directory')
    args = parser.parse_args()
    config = yaml.safe_load((ROOT / 'packaging/nfpm/nfpm.yaml').read_text())
    version = runpy.run_path(str(ROOT / 'src/musicbee_linux/__init__.py'))['__version__']
    pkgbuild, srcinfo = generate(config, version, args.commit)
    args.output.mkdir(parents=True, exist_ok=True)
    (args.output / 'PKGBUILD').write_text(pkgbuild, encoding='utf-8')
    (args.output / '.SRCINFO').write_text(srcinfo, encoding='utf-8')


if __name__ == '__main__':
    main()
